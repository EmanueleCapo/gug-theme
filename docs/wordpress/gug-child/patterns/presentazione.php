<div class="wp-block-group gug-prose gug-prose--columns"><!-- wp:paragraph -->
<p>Le attività agonistiche delle specialità controllate dalla Federazione Italiana Nuoto sono disciplinate dalle norme internazionali emanate FINA (federazione mondiale), integrate da quelle stabilite dalla FIN stessa. Il controllo circa la corretta applicazione di detti regolamenti è demandato agli Ufficiali Gara.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Il Gruppo Ufficiali Gara è l'organo, di rilievo statutario, che prepara ed aggiorna gli ufficiali gara italiani, i quali si suddividono in diverse categorie: arbitri di pallanuoto, giudici di nuoto, tuffi, sincro e salvamento.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Esso ha lo scopo di reclutare, organizzare e disciplinare gli Ufficiali Gara della F.I.N. e di provvedere, per loro mezzo, alla esatta applicazione dei Regolamenti tecnici e delle relative norme federali.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>La formazione di tali figure è di competenza del Gruppo Ufficiali Gara nelle sue articolazioni regionali, che provvedono alla organizzazione di corsi secondo le direttive emanate dalla FIN sulla base di un calendario che tiene conto delle diverse situazioni locali.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>La carriera dell'ufficiale gara consente a chi è stato un atleta di continuare a frequentare il proprio ambiente preferito. Permette, a chi è interessato, di ottenere una maggior conoscenza delle discipline FIN.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>L'attività svolta dagli Ufficiali Gara è importante a tutti i livelli di esperienza e consente ai soggetti particolarmente esperti di frequentare competizioni internazionali, anche ad altissimo livello. Ufficiali gara italiani partecipano infatti regolarmente a Giochi Olimpici, Campionati del Mondo e a tutte le altre manifestazioni internazionali di discipline FIN.</p>
